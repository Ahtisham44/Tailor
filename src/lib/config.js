// ── Custom categories: flattened catalogue of every standard measurement field ──
// Built from MEAS_GROUPS (excludes special selector groups: gala/SQ style).
// Used by the category manager (checkbox picker) and to resolve a custom
// category's measurement fields in the order form.
export const FIELD_CATALOGUE = Object.entries(MEAS_GROUPS)
  .filter(([, g]) => !g.isGalaSelect && !g.isSQStyle && Array.isArray(g.fields) && g.fields.length)
  .map(([gkey, g]) => ({
    group: gkey,
    groupLabel: g.label,
    fields: g.fields.map(f => ({ key: f.key, label: f.label, noFrac: !!f.noFrac })),
  }))

// Flat key→field lookup across all groups.
export const FIELD_BY_KEY = {}
FIELD_CATALOGUE.forEach(grp => grp.fields.forEach(f => { FIELD_BY_KEY[f.key] = { ...f, group: grp.group, groupLabel: grp.groupLabel } }))

// Resolve the measurement fields for a category.
// Built-in categories use CATS/MEAS_GROUPS; custom categories use their
// stored meas_fields (array of field keys). Returns an array of field objects.
export function resolveCategoryFields(catName, catRow) {
  if (CATS[catName]) {
    const out = []
    CATS[catName].groups.forEach(gkey => {
      const g = MEAS_GROUPS[gkey]
      if (g && Array.isArray(g.fields)) g.fields.forEach(f => out.push(f))
    })
    return out
  }
  // Custom category: use stored meas_fields keys
  const keys = (catRow && catRow.meas_fields) || []
  return keys.map(k => FIELD_BY_KEY[k]).filter(Boolean)
}

