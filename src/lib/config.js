import { UR_PHRASES } from "@/lib/i18n"

export function tr(key, lang) {
  const direct = LABELS[lang] && LABELS[lang][key]
  if (direct) return direct
  const en = LABELS.en[key]
  // In Urdu, if there's no ur entry for this key, try translating the English
  // label via the shared phrase dictionary before falling back to English.
  if (lang === "ur" && en && UR_PHRASES[en]) return UR_PHRASES[en]
  return en || key
}

